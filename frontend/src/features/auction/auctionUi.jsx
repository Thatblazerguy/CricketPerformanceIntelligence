/**
 * Shared Auction Intelligence UI: price formatting, provenance labels, filters
 * and the player valuation drawer.
 *
 * Four price notions are always visually distinct:
 *   Actual (historical record) · Market value (performance-implied) ·
 *   Predicted price (model range) · Simulated price (auction room only).
 */
import { useEffect, useState } from 'react';
import { auctionAnalytics } from '../../services/api';
import { Badge, Button, Callout, ErrorState, FilterBar, FilterField, LoadingSpinner, Select } from '../../components/ui';
import Icon from '../../components/icons';

export const DASH = '—';
const isNum = v => v !== null && v !== undefined && Number.isFinite(Number(v));

/** INR lakh → "₹12.5 cr" / "₹75 L". */
export function fmtL(v, { short = false } = {}) {
  if (!isNum(v)) return DASH;
  const n = Number(v);
  if (Math.abs(n) >= 100) return `₹${(n / 100).toFixed(n >= 1000 ? 1 : 2).replace(/\.?0+$/, '')}${short ? 'c' : ' cr'}`;
  return `₹${Math.round(n)}${short ? 'L' : ' L'}`;
}
export const fmtPct = (v, d = 0) => (isNum(v) ? `${(Number(v) * 100).toFixed(d)}%` : DASH);
export const fmtNum = (v, d = 1) => (isNum(v) ? Number(v).toFixed(d) : DASH);
export const ROLE_LABEL = { BAT: 'Batter', BOWL: 'Bowler', AR: 'All-rounder', WK: 'Wicketkeeper', UNK: 'Unknown', Unknown: 'Unknown' };
export const roleLabel = r => ROLE_LABEL[r] || r || 'Unknown';

const KIND = {
  actual: { label: 'Actual', variant: 'default', title: 'Recorded historical outcome from the cited sources' },
  verified: { label: 'Verified', variant: 'green', title: 'Corroborated by two or more independent sources' },
  single: { label: 'Single source', variant: 'amber', title: 'Recorded by one source only — not independently verified' },
  conflict: { label: 'Conflict', variant: 'red', title: 'Sources disagree; excluded from model training' },
  calculated: { label: 'Calculated', variant: 'blue', title: 'Computed from ball-by-ball records' },
  model: { label: 'Model estimate', variant: 'indigo', title: 'Generated by CPI models — an estimate, not a fact' },
  inferred: { label: 'Inferred', variant: 'amber', title: 'Inferred from indirect evidence' },
  simulated: { label: 'Simulated', variant: 'gold', title: 'Produced by the auction simulator' },
  derived: { label: 'Derived', variant: 'amber', title: 'Derived from other recorded figures' },
};
export function Prov({ kind, children }) {
  const k = KIND[kind] || KIND.model;
  return <Badge variant={k.variant} className="cursor-help" ><span title={k.title}>{children || k.label}</span></Badge>;
}
export const verificationKind = v => (v === 'corroborated' ? 'verified' : v === 'conflict' ? 'conflict' : 'single');

/** Horizontal p10–p90 range with the p50 tick and optional actual marker. */
export function PriceRange({ p10, p50, p90, actual, max, base, compact = false }) {
  if (!isNum(p50)) return <span className="text-slate-600">{DASH}</span>;
  const top = Math.max(max || 0, p90 || 0, actual || 0, 1);
  const pos = v => `${Math.min(100, (Number(v) / top) * 100)}%`;
  return (
    <div className={compact ? 'w-36' : 'w-full'} title={`Predicted ${fmtL(p10)}–${fmtL(p90)} (median ${fmtL(p50)})${isNum(actual) ? ` · actual ${fmtL(actual)}` : ''}`}>
      <div className="relative h-2 rounded-full bg-[var(--chart-track)]">
        {isNum(p10) && isNum(p90) && <div className="absolute h-full rounded-full bg-accent/35" style={{ left: pos(p10), width: `calc(${pos(p90)} - ${pos(p10)})` }} />}
        {isNum(base) && <div className="absolute -top-0.5 h-3 w-px bg-slate-500" style={{ left: pos(base) }} />}
        <div className="absolute -top-1 h-4 w-[3px] -translate-x-1/2 rounded-full bg-accent-soft" style={{ left: pos(p50) }} />
        {isNum(actual) && <div className="absolute -top-1 h-4 w-4 -translate-x-1/2 rotate-45 scale-50 bg-[var(--c3)]" style={{ left: pos(actual) }} />}
      </div>
      {!compact && <div className="num mt-1 flex justify-between text-2xs text-slate-500"><span>{fmtL(p10)}</span><span className="text-slate-200">{fmtL(p50)}</span><span>{fmtL(p90)}</span></div>}
    </div>
  );
}

export const ConfidenceBadge = ({ value }) => value ? <Badge variant={value === 'high' ? 'green' : value === 'medium' ? 'blue' : 'amber'}>{value} confidence</Badge> : null;

export function useAsync(fn, deps) {
  const [state, setState] = useState({ data: null, error: '', loading: true });
  useEffect(() => {
    let alive = true;
    setState(s => ({ ...s, loading: true, error: '' }));
    fn().then(data => alive && setState({ data, error: '', loading: false }))
      .catch(e => alive && setState({ data: null, error: e.message || 'Request failed', loading: false }));
    return () => { alive = false; };
  }, deps); // eslint-disable-line react-hooks/exhaustive-deps
  return state;
}

export const EMPTY_FILTERS = { role: '', overseas: '', search: '', min_base: '', max_base: '', min_pred: '', max_pred: '', min_ipl: '', max_ipl: '', tag: '' };
export const activeFilterCount = f => Object.entries(f).filter(([, v]) => v !== '' && v !== null && v !== undefined).length;
export const filterParams = f => ({ ...f, overseas: f.overseas === '' ? undefined : f.overseas });

const TAGS = [['top_order', 'Top order'], ['middle_order', 'Middle order'], ['finisher', 'Finisher'], ['wicketkeeper', 'Wicketkeeper'],
  ['pace', 'Pace'], ['spin', 'Spin'], ['death_bowler', 'Death bowler'], ['powerplay_bowler', 'Powerplay bowler'], ['all_rounder', 'All-rounder']];

/** One filter bar shared by Market and Valuation so filters stay consistent. */
export function PlayerFilterBar({ filters, setFilters, records, total }) {
  const set = k => v => setFilters(f => ({ ...f, [k]: v }));
  const num = k => <input type="number" inputMode="decimal" value={filters[k]} onChange={e => set(k)(e.target.value)} className="h-9 w-24 text-[13px]" />;
  return (
    <FilterBar onReset={() => setFilters(EMPTY_FILTERS)} active={activeFilterCount(filters)}
      note={records !== undefined ? `${records.toLocaleString()} of ${total?.toLocaleString?.() ?? total} pool players match — every metric, chart and list below uses only these records. Prices in INR lakh (100 L = ₹1 cr).` : undefined}>
      <FilterField label="Search"><input type="search" value={filters.search} onChange={e => set('search')(e.target.value)} placeholder="Player name" className="h-9 w-44 text-[13px]" /></FilterField>
      <FilterField label="Role"><Select value={filters.role} onChange={set('role')} placeholder="All roles" options={Object.entries(ROLE_LABEL).slice(0, 4).map(([id, label]) => ({ id, label }))} /></FilterField>
      <FilterField label="Origin"><Select value={filters.overseas} onChange={set('overseas')} placeholder="All" options={[{ id: 'false', label: 'Domestic' }, { id: 'true', label: 'Overseas' }]} /></FilterField>
      <FilterField label="Profile"><Select value={filters.tag} onChange={set('tag')} placeholder="Any" options={TAGS.map(([id, label]) => ({ id, label }))} /></FilterField>
      <FilterField label="Base min (L)">{num('min_base')}</FilterField>
      <FilterField label="Base max (L)">{num('max_base')}</FilterField>
      <FilterField label="Predicted min (L)">{num('min_pred')}</FilterField>
      <FilterField label="Predicted max (L)">{num('max_pred')}</FilterField>
      <FilterField label="IPL matches ≥">{num('min_ipl')}</FilterField>
      <FilterField label="IPL matches ≤">{num('max_ipl')}</FilterField>
    </FilterBar>
  );
}

export function ContextNotes({ context }) {
  if (!context?.notes?.length) return null;
  return <Callout tone="warn">{context.notes.join(' ')}</Callout>;
}

/** Slide-over with a player's full valuation, evidence, alternatives and franchise interest. */
export function PlayerDrawer({ context, playerKey, onClose }) {
  const { data, error, loading } = useAsync(() => (playerKey ? auctionAnalytics.player(context, playerKey) : Promise.resolve(null)), [context, playerKey]);
  useEffect(() => {
    if (!playerKey) return undefined;
    const onKey = e => e.key === 'Escape' && onClose();
    window.addEventListener('keydown', onKey);
    return () => window.removeEventListener('keydown', onKey);
  }, [playerKey, onClose]);
  if (!playerKey) return null;
  const p = data?.player;
  const f = data?.features || {};
  return (
    <div className="fixed inset-0 z-50 flex justify-end" role="dialog" aria-modal="true" aria-label="Player valuation">
      <button className="absolute inset-0 bg-black/50 backdrop-blur-[2px]" aria-label="Close" onClick={onClose} />
      <aside className="relative h-full w-full max-w-2xl overflow-y-auto border-l border-line bg-surface p-5 shadow-2xl animate-fade-in sm:p-6">
        <div className="mb-4 flex items-start justify-between gap-3">
          <div className="min-w-0">
            <p className="eyebrow mb-1">Player valuation</p>
            <h2 className="truncate text-xl font-semibold text-white">{p?.name || 'Loading…'}</h2>
            {p && <div className="mt-2 flex flex-wrap gap-1.5">
              <Badge>{roleLabel(p.role)}</Badge>
              {p.overseas !== null && <Badge variant={p.overseas ? 'blue' : 'default'}>{p.overseas ? 'Overseas' : 'Domestic'}</Badge>}
              {p.bowling_kind && <Badge>{p.bowling_kind}</Badge>}
              {p.set_code && <Badge>Set {p.set_code}</Badge>}
              <ConfidenceBadge value={p.confidence} />
            </div>}
          </div>
          <Button variant="icon" onClick={onClose} aria-label="Close"><Icon name="close" size={16} /></Button>
        </div>
        {loading && <LoadingSpinner message="Valuing player…" />}
        {error && <ErrorState message={error} />}
        {p && (
          <div className="space-y-5">
            <div className="grid grid-cols-2 gap-3 sm:grid-cols-4">
              <PriceTile label="Base price" value={fmtL(p.base_lakh)} kind="actual" />
              <PriceTile label="Market value" value={fmtL(p.market_value_lakh)} kind="model" sub="Performance-implied" />
              <PriceTile label="Predicted price" value={fmtL(p.predicted.p50)} kind="model" sub={`${fmtL(p.predicted.p10)}–${fmtL(p.predicted.p90)}`} />
              <PriceTile label="Actual price" value={p.actual ? (p.actual.status === 'SOLD' ? fmtL(p.actual.price_lakh) : p.actual.status) : DASH}
                kind="actual" sub={p.actual?.franchise || (p.actual ? '' : 'Not a replay')} />
            </div>
            <PriceRange p10={p.predicted.p10} p50={p.predicted.p50} p90={p.predicted.p90} actual={p.actual?.price_lakh} base={p.base_lakh} />
            <div className="grid grid-cols-2 gap-x-6 gap-y-2 text-xs sm:grid-cols-3">
              <KV k="Quality" v={fmtNum(p.quality, 0)} hint="Role-relevant, pool-relative (0–100)" />
              <KV k="Batting / bowling" v={`${fmtNum(p.bat_quality, 0)} / ${fmtNum(p.bowl_quality, 0)}`} />
              <KV k="Scarcity" v={p.scarcity ? `${fmtNum(p.scarcity.score, 0)} · ${p.scarcity.group}` : DASH} />
              <KV k="Bidding-war probability" v={fmtPct(p.bidding_war_probability)} hint="P(price ≥ 3× base)" />
              <KV k="Sale probability" v={fmtPct(p.sale_probability)} hint="Experimental — see Backtesting" />
              <KV k="Market premium" v={p.market_premium ? `${p.market_premium.toFixed(2)}×` : DASH} hint="Predicted ÷ performance-implied" />
              <KV k="IPL matches (before)" v={p.ipl_matches ?? DASH} />
              <KV k="IPL suitability" v={fmtNum(p.ipl_suitability, 0)} />
              <KV k="Evidence" v={`${p.evidence_balls ?? 0} balls`} hint="IPL-equivalent, recency-weighted" />
            </div>
            {data.explanation?.length > 0 && <Section title="Why this valuation" tag="calculated">
              <ul className="list-disc space-y-1 pl-4 text-xs leading-relaxed text-slate-300">{data.explanation.map((x, i) => <li key={i}>{x}</li>)}</ul>
            </Section>}
            {p.missing_information?.length > 0 && <Callout tone="warn">Missing information: {p.missing_information.join('; ')}.</Callout>}
            <Section title="Supporting statistics" tag="calculated" note={`Men's T20 + T20I, 3 years before ${f.as_of || 'the auction'}. Non-IPL competitions converted to an IPL-equivalent scale.`}>
              <div className="grid grid-cols-2 gap-x-6 gap-y-1.5 text-xs sm:grid-cols-3">
                {[['SR (eq.)', f.bat_sr_eq], ['Average (eq.)', f.bat_avg_eq], ['Boundary %', f.bat_boundary_pct], ['Dot %', f.bat_dot_pct], ['Powerplay SR', f.bat_pp_sr], ['Death SR', f.bat_death_sr],
                  ['vs pace SR', f.bat_vs_pace_sr], ['vs spin SR', f.bat_vs_spin_sr], ['Chasing SR', f.bat_chase_sr], ['Economy (eq.)', f.bowl_econ_eq], ['Bowling SR', f.bowl_sr_eq], ['Bowling dot %', f.bowl_dot_pct],
                  ['PP economy', f.bowl_pp_econ], ['Death economy', f.bowl_death_econ], ['Death-overs share', f.bowl_death_share], ['T20 balls faced', f.t20_bat_balls], ['T20 balls bowled', f.t20_bowl_balls], ['Competitions', f.competitions_used]]
                  .map(([k, v]) => <KV key={k} k={k} v={isNum(v) ? (Number.isInteger(v) ? v : Number(v).toFixed(2)) : DASH} />)}
              </div>
            </Section>
            <Section title="Alternatives in this pool" tag="model">
              {!data.alternatives?.length ? <p className="text-xs text-slate-500">No similar-profile alternatives remain.</p> : (
                <table className="w-full text-xs"><thead><tr className="text-left text-slate-500"><th className="py-1">Player</th><th>Shared profile</th><th className="text-right">Quality</th><th className="text-right">Predicted</th></tr></thead>
                  <tbody>{data.alternatives.map(a => <tr key={a.name} className="border-t border-line-soft"><td className="py-1.5 text-slate-200">{a.name}{a.cheaper && <Badge variant="green" className="ml-1.5">cheaper</Badge>}{a.better_output && <Badge variant="blue" className="ml-1">better output</Badge>}</td>
                    <td className="text-slate-400">{a.shared_profile.join(', ') || roleLabel(a.role)}</td><td className="num text-right">{fmtNum(a.quality, 0)}</td><td className="num text-right">{fmtL(a.p50)}</td></tr>)}</tbody></table>)}
            </Section>
            <Section title="Which franchises need him" tag="model" note="Need = best-XI improvement plus depth for unmet needs, from each franchise's actual squad.">
              <div className="space-y-1.5">{data.franchise_interest.map(r => (
                <div key={r.franchise} className="flex items-center gap-3 text-xs">
                  <span className="w-12 font-medium text-slate-200">{r.franchise}</span>
                  <div className="h-1.5 flex-1 rounded-full bg-[var(--chart-track)]"><div className="h-full rounded-full bg-accent" style={{ width: `${Math.min(100, r.need_score / 1.6 * 100)}%`, opacity: r.eligible ? 1 : 0.3 }} /></div>
                  <span className="num w-16 text-right text-slate-400">ΔXI {r.marginal.xi_delta > 0 ? '+' : ''}{r.marginal.xi_delta}</span>
                  <span className="num w-20 text-right text-slate-500">{r.eligible ? `max ${fmtL(r.max_bid_lakh, { short: true })}` : 'ineligible'}</span>
                </div>))}</div>
            </Section>
            {data.auction_history?.length > 0 && <Section title="Auction history" tag="actual">
              <table className="w-full text-xs"><tbody>{data.auction_history.map((h, i) => (
                <tr key={i} className={`border-t border-line-soft ${h.future_of_context ? 'opacity-50' : ''}`}>
                  <td className="num py-1.5">{h.season}</td><td>{h.status}</td><td>{h.franchise || DASH}</td><td className="num text-right">{fmtL(h.price_lakh)}</td>
                  <td className="text-right"><Prov kind={verificationKind(h.verification)} /></td>
                  <td className="text-right text-2xs text-slate-500">{h.future_of_context ? 'after this auction' : ''}</td></tr>))}</tbody></table>
            </Section>}
            <p className="text-2xs text-slate-500">Model: {data.model?.version} · trained on {data.model?.trained_on}.</p>
          </div>
        )}
      </aside>
    </div>
  );
}

function PriceTile({ label, value, sub, kind }) {
  return (
    <div className="rounded-2xl border border-line bg-surface-raised px-3 py-2.5">
      <div className="mb-1 flex items-center justify-between gap-1"><span className="truncate text-2xs text-slate-500">{label}</span><Prov kind={kind} /></div>
      <div className="display-num text-lg text-white">{value}</div>
      {sub && <div className="num truncate text-2xs text-slate-500">{sub}</div>}
    </div>
  );
}
export function KV({ k, v, hint }) {
  return <div className="flex min-w-0 justify-between gap-2 border-b border-line-soft py-1" title={hint}><span className="truncate text-slate-500">{k}</span><span className="num shrink-0 text-slate-200">{v}</span></div>;
}
export function Section({ title, tag, note, children }) {
  return (
    <section>
      <div className="mb-2 flex items-center justify-between gap-2"><h3 className="text-[13px] font-semibold text-white">{title}</h3>{tag && <Prov kind={tag} />}</div>
      {children}
      {note && <p className="mt-1.5 text-2xs leading-relaxed text-slate-500">{note}</p>}
    </section>
  );
}

export function PriorityBadge({ priority }) {
  const v = { Critical: 'red', High: 'amber', Medium: 'blue', Low: 'default' }[priority] || 'default';
  return <Badge variant={v}>{priority}</Badge>;
}
